-- פירוק פנימי של פרויקט לתת-פרויקטים, לפי שם המודעה.
--
-- הרקע: לקוח שמי נדל"ן מנוהל בחשבון מודעות אחד, עם שני קמפיינים בלבד
-- (טסטינג + סקיילינג). שם הבניין מופיע ברמת המודעה, לא ברמת הקמפיין.
-- הלקוח רוצה לראות בדשבורד גם את הסכום הכולל של החשבון וגם פירוק לפי בניין,
-- באותו מסך - ולכן זה לא 8 פרויקטים נפרדים אלא פרויקט אחד עם פירוק פנימי.
--
-- שמונה פרויקטים נפרדים היו סופרים כל שקל וכל ליד פעמיים ברמת הלקוח.
-- פירוק פנימי נותן את אותו המידע בלי הכפילות.
--
-- NULL או מערך ריק = ההתנהגות הישנה בדיוק. אף פרויקט קיים לא מושפע.

alter table public.projects
  add column if not exists sub_projects jsonb;

comment on column public.projects.sub_projects is
  'מערך JSON של שמות תת-פרויקטים. כשמוגדר, סנכרון מטא מפלח את שורות הפרויקט לפי הכלת השם בשם המודעה, ושומר את התוצאה ב-summary.bySubProject. מה שלא נתפס נכנס לדלי "ללא שיוך".';

-- ── שמי נדל"ן: שמונת הבניינים ──────────────────────────────────────────────
-- הסדר לא משנה - ההתאמה תמיד מהשם הארוך לקצר, כדי ש"שמי כללי" לא ייבלע.
update public.projects
set sub_projects = '["שמי כללי","שם טוב","צהל","בן דוד","סוקולוב","הצוערים","שבאזי","קלישר"]'::jsonb
where name = 'כלל הפרויקטים'
  and meta_account_id = '395927933298639';

