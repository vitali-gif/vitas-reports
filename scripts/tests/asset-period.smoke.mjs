import { bestPeriodKey, keySpan } from '../../lib/ads/range-rows.js'

const fail = (m) => { console.error('✗ ' + m); process.exitCode = 1 }
const eq = (label, a, b) => (JSON.stringify(a) === JSON.stringify(b) ? console.log('✓ ' + label) : fail(`${label}: got ${JSON.stringify(a)}, expected ${JSON.stringify(b)}`))

eq('חודש → טווח ימים', keySpan('2026-09'), ['2026-09-01', '2026-09-30'])
eq('פברואר', keySpan('2026-02'), ['2026-02-01', '2026-02-28'])
eq('טווח נשאר טווח', keySpan('2026-09-24_2026-09-30'), ['2026-09-24', '2026-09-30'])
eq('מפתח לא מוכר', keySpan('weird'), null)

// המפתחות שהקרון שומר בפועל (1.10): חודשים, רבעונים, וטווחים מוכנים.
const keys = ['2026-10', '2026-09', '2026-08', '2026-07-01_2026-09-30', '2026-10-01_2026-12-31', '2026-10-01_2026-10-01',
  '2026-09-30_2026-09-30', '2026-09-24_2026-09-30', '2026-09-01_2026-09-30', '2026-01-01_2026-03-31']

eq('טווח בתוך ספטמבר → ספטמבר (הקטן שמכיל, לא הרבעון)', bestPeriodKey(keys, '2026-09-10', '2026-09-15'), '2026-09')
eq('השבוע האחרון → בדיוק השבוע השמור', bestPeriodKey(keys, '2026-09-24', '2026-09-30'), '2026-09-24_2026-09-30')
eq('היום → בדיוק היום', bestPeriodKey(keys, '2026-10-01', '2026-10-01'), '2026-10-01_2026-10-01')
// אין תקופה שמכילה; ספטמבר והשבוע 24–30 חופפים 6 ימים כל אחד — השבוע קרוב יותר באורך לטווח, ולכן מייצג יותר.
eq('חוצה חודשים (25.9–5.10) → החפיפה הגדולה, ובתיקו הקצר יותר', bestPeriodKey(keys, '2026-09-25', '2026-10-05'), '2026-09-24_2026-09-30')
eq('חוצה חודשים עם רוב באוקטובר (28.9–20.10) → אוקטובר', bestPeriodKey(keys, '2026-09-28', '2026-10-20'), '2026-10')
eq('יולי–אוגוסט → הרבעון שמכיל את שניהם', bestPeriodKey(keys, '2026-07-15', '2026-08-20'), '2026-07-01_2026-09-30')
eq('בלי שום חפיפה → אין', bestPeriodKey(['2026-01'], '2026-09-01', '2026-09-05'), null)
eq('מפתחות לא מוכרים מדולגים', bestPeriodKey(['weird', '2026-09'], '2026-09-01', '2026-09-05'), '2026-09')

if (!process.exitCode) console.log('\n✓ בחירת התקופה לקבוצות הנכסים תקינה')
