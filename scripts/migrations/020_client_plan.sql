--
-- למה
-- ───
-- עד עכשיו לא היה במערכת שום מושג של "מנוי" — לא בקוד ולא בסכימה. כל פיצ'ר שהיה
-- קיים היה קיים לכולם. "ישיבות שיווק" הוא הראשון שנמכר בנפרד, ולכן צריך מקור אמת
-- אחד לשאלה "האם ללקוח הזה מותר".
--
-- למה על clients ולא על projects
-- ──────────────────────────────
-- המנוי הוא יחס מסחרי עם הלקוח, לא תכונה של פרויקט. ללקוח עם שלושה פרויקטים יש
-- חוזה אחד, ולא היה הגיוני שיקבל ישיבות בפרויקט אחד ולא באחר. פרויקט מגיע ללקוח
-- שלו דרך projects.client_id, ולכן אפשר תמיד לגזור את המנוי מהפרויקט.
--
-- ערכים
-- ─────
--   'basic'  — ברירת המחדל. כל הלקוחות הקיימים מקבלים אותה.
--   'pro'    — פותח את טאב "ישיבות שיווק".
-- ה-CHECK קיים כדי שטעות הקלדה ('Pro', 'premium') לא תיצור בשקט מנוי שלישי.
-- הקוד מנרמל בכל מקרה: כל מה שאינו 'pro' נחשב 'basic' (fail-closed).
--
-- מה זה לא
-- ────────
-- זה לא חיוב, לא תאריך תפוגה ולא היסטוריית מנויים. עמודה אחת, שוויטלי מעדכן ידנית
-- כשלקוח משדרג. אם בעתיד יהיה צורך בתאריכי התחלה/סיום — זו טבלה נפרדת, לא כאן.
--
-- אכיפה
-- ─────
-- העמודה הזאת נקראת בשרת בלבד, ב-lib/auth.js (requireProjectPlan), וכל נתיבי
-- /api/meetings* ו-/api/meeting-tasks/* עוברים דרכה. התגית "PRO" בממשק היא שילוט,
-- לא הרשאה — בדיוק כמו שכתוב ב-CLAUDE.md.
--
-- RLS: אין שינוי. clients כבר מוגן ממיגרציה 001, והוספת עמודה אינה נוגעת במדיניות.
-- ════════════════════════════════════════════════════════════════════════════

begin;

alter table public.clients
  add column if not exists plan text not null default 'basic';

alter table public.clients
  drop constraint if exists clients_plan_check;

alter table public.clients
  add constraint clients_plan_check check (plan in ('basic', 'pro'));

comment on column public.clients.plan is
  'מנוי הלקוח: basic (ברירת מחדל) או pro. pro פותח את טאב "ישיבות שיווק". נאכף ב-lib/auth.js.';

commit;

