export const ALL_STEPS = STAGES.flatMap(s => s.steps.map(st => ({ ...st, stage: s.key })))
export const STEP_KEYS = new Set(ALL_STEPS.map(s => s.key))

/**
 * סיכום לפרויקט: states = { [step]: { status, ... } }, auto = { [autoKey]: true/false }.
 * שלב נחשב סגור כשהוא done / na, או כשהבדיקה האוטומטית שלו עברה ואין עליו סטטוס ידני אחר.
 * מחזיר { done, total, pct, currentStage: {key,title} | null }.
 */
export function stepDone(step, states, auto) {
  const st = states?.[step.key]?.status
  if (st === 'done' || st === 'na') return true
  if (st === 'todo' || st === 'doing') return false
  return !!(step.auto && auto?.[step.auto])
}
export function onboardingSummary(states, auto) {
  let done = 0
  let currentStage = null
  for (const stage of STAGES) {
    const left = stage.steps.filter(s => !stepDone(s, states, auto)).length
    done += stage.steps.length - left
    if (left && !currentStage) currentStage = { key: stage.key, title: stage.title }
  }
  const total = ALL_STEPS.length
  return { done, total, pct: Math.round((done / total) * 100), currentStage }
}
