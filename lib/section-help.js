const norm = (s) => String(s || '').replace(/[‎‏]/g, '').replace(/\s+/g, ' ').trim()

/** הטקסט לכותרת (לפי תחילת הכותרת), או null. */
export function helpFor(title) {
  const t = norm(title)
  if (!t) return null
  const hit = SECTION_HELP.find(([k]) => t.startsWith(k))
  return hit ? hit[1] : null
}
